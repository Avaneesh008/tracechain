"""Generate markdown result tables in reports/RESULTS.md from JSON metrics.

Implements SPEC section 6 and P3 requirement to generate tables from code, not by hand.
"""

from __future__ import annotations

import json
from pathlib import Path


REPORTS_DIR = Path("reports")
ARTIFACTS_DIR = Path("artifacts")
METRICS_JSON = REPORTS_DIR / "metrics.json"
PREPARED_JSON = ARTIFACTS_DIR / "prepared_metadata.json"
ATTRIBUTION_JSON = REPORTS_DIR / "attribution_stats.json"
RESULTS_MD = REPORTS_DIR / "RESULTS.md"


def format_cm(cm: dict[str, int]) -> str:
    """Format confusion matrix as string: TP=..., FP=..., FN=..., TN=..."""
    return f"TP={cm.get('tp', 0):,}, FP={cm.get('fp', 0):,}, FN={cm.get('fn', 0):,}, TN={cm.get('tn', 0):,}"


def generate_results_markdown() -> str:
    """Read metrics and metadata JSON files and return formatted markdown content."""
    lines: list[str] = [
        "# TraceChain - Model Evaluation Results",
        "",
        "Auto-generated by `scripts/04_make_results.py`. Do not edit by hand.",
        "",
    ]

    # 1. Dataset & Leakage Summary (if prepared_metadata.json exists)
    if PREPARED_JSON.is_file():
        with PREPARED_JSON.open("r", encoding="utf-8") as f:
            prep_data = json.load(f)

        lines.extend(
            [
                "## 1. Dataset Splits & Leakage Summary",
                "",
                f"- **Total Addresses in Graph**: {prep_data.get('total_addresses', 0):,}",
                f"- **Total Directed Edges**: {prep_data.get('total_edges', 0):,}",
                f"- **Data Prep Pipeline Runtime**: {prep_data.get('run_time_seconds', 0.0):.2f} seconds",
                f"- **Data Prep Peak Memory**: {prep_data.get('peak_memory_mb', 0.0):.2f} MB",
                "",
                "| Split | Time Steps | Rows | Unique Addresses | Illicit (1) | Licit (0) | Illicit Share |",
                "| :--- | :--- | ---: | ---: | ---: | ---: | ---: |",
            ]
        )
        splits = prep_data.get("splits", {})
        for split_key, split_name in [
            ("train", "Train"),
            ("test_all", "Test (All)"),
            ("test_cold", "Test (Cold subset)"),
        ]:
            s = splits.get(split_key, {})
            lines.append(
                f"| **{split_name}** | {s.get('timesteps', '-')} | "
                f"{s.get('rows', 0):,} | {s.get('unique_addresses', 0):,} | "
                f"{s.get('illicit_count', 0):,} | {s.get('licit_count', 0):,} | "
                f"{s.get('illicit_share', 0.0)*100:.2f}% |"
            )

        leak = prep_data.get("leakage", {})
        lines.extend(
            [
                "",
                "### Temporal Leakage Analysis",
                f"- **Total Test Addresses**: {leak.get('test_addresses_total', 0):,}",
                f"- **Addresses Seen in Training Period (Leakage / Warm)**: {leak.get('overlap_with_train_addresses', 0):,} ({leak.get('overlap_address_share', 0.0)*100:.2f}%)",
                f"- **Cold Test Addresses (Never Seen in Training)**: {leak.get('cold_test_addresses', 0):,} ({leak.get('cold_address_share', 0.0)*100:.2f}%)",
                "",
            ]
        )

    # 2. VASP Attribution Summary (if attribution_stats.json exists)
    if ATTRIBUTION_JSON.is_file():
        with ATTRIBUTION_JSON.open("r", encoding="utf-8") as f:
            attr_data = json.load(f)

        act = attr_data.get("active_index_stats", {})
        sens = attr_data.get("sensitivity_by_k", {})

        lines.extend(
            [
                "## 2. VASP Attribution & Shortest-Path Reachability (SPEC Section 4.3)",
                "",
                f"- **Active Seeds Count (K)**: {attr_data.get('default_k', 30)} ({attr_data.get('seed_kind', 'proxy')} seeds)",
                f"- **Reachable Addresses**: {act.get('reachable_addresses', 0):,} / {act.get('total_addresses', 0):,} ({act.get('reachable_share', 0.0)*100:.2f}%)",
                f"- **Unattributed (Disconnected)**: {act.get('unattributed_addresses', 0)}",
                f"- **Median Hops to Nearest Seed**: Illicit = {act.get('median_hops_illicit', 0.0)} hops | Licit = {act.get('median_hops_licit', 0.0)} hops",
                "",
                "### Reachability Sensitivity by Number of Proxy Seeds (K)",
                "",
                "| Number of Seeds (K) | Reachable <= 2 Hops | Reachable <= 4 Hops | Reachable <= 6 Hops | Median Hops (Illicit) | Median Hops (Licit) |",
                "| :--- | ---: | ---: | ---: | ---: | ---: |",
            ]
        )

        for k_val in ["10", "30", "100"]:
            k_entry = sens.get(k_val, {})
            lines.append(
                f"| **K = {k_val}** | "
                f"{k_entry.get('reachable_within_2_hops_share', 0.0)*100:.2f}% ({k_entry.get('reachable_within_2_hops_count', 0):,}) | "
                f"{k_entry.get('reachable_within_4_hops_share', 0.0)*100:.2f}% ({k_entry.get('reachable_within_4_hops_count', 0):,}) | "
                f"{k_entry.get('reachable_within_6_hops_share', 0.0)*100:.2f}% ({k_entry.get('reachable_within_6_hops_count', 0):,}) | "
                f"{k_entry.get('median_hops_illicit', 0.0)} | "
                f"{k_entry.get('median_hops_licit', 0.0)} |"
            )

        lines.append("")

    # 3. Model Performance Comparison
    if METRICS_JSON.is_file():
        with METRICS_JSON.open("r", encoding="utf-8") as f:
            metrics_data = json.load(f)

        base = metrics_data.get("baseline", {})
        graph = metrics_data.get("graph_enhanced", {})

        has_base = bool(base)
        has_graph = bool(graph)

        lines.extend(
            [
                "## 3. Model Performance Comparison (Illicit Class, Threshold = 0.5)",
                "",
                "| Metric | Baseline (All Test) | Baseline (Cold Test) | Graph-Enhanced (All Test) | Graph-Enhanced (Cold Test) |",
                "| :--- | ---: | ---: | ---: | ---: |",
            ]
        )

        base_all = base.get("test_all", {}) if has_base else {}
        base_cold = base.get("test_cold", {}) if has_base else {}
        graph_all = graph.get("test_all", {}) if has_graph else {}
        graph_cold = graph.get("test_cold", {}) if has_graph else {}

        def get_val(d: dict, key: str, fmt: str = ".4f") -> str:
            if not d or key not in d:
                return "Pending"
            v = d[key]
            return f"{v:{fmt}}" if isinstance(v, float) else f"{v:,}"

        lines.append(f"| **Precision** | {get_val(base_all, 'precision')} | {get_val(base_cold, 'precision')} | {get_val(graph_all, 'precision')} | {get_val(graph_cold, 'precision')} |")
        lines.append(f"| **Recall** | {get_val(base_all, 'recall')} | {get_val(base_cold, 'recall')} | {get_val(graph_all, 'recall')} | {get_val(graph_cold, 'recall')} |")
        lines.append(f"| **F1 Score** | {get_val(base_all, 'f1')} | {get_val(base_cold, 'f1')} | {get_val(graph_all, 'f1')} | {get_val(graph_cold, 'f1')} |")
        lines.append(f"| **PR-AUC** | {get_val(base_all, 'pr_auc')} | {get_val(base_cold, 'pr_auc')} | {get_val(graph_all, 'pr_auc')} | {get_val(graph_cold, 'pr_auc')} |")
        lines.append(f"| **Evaluated Rows** | {get_val(base_all, 'rows', 'd')} | {get_val(base_cold, 'rows', 'd')} | {get_val(graph_all, 'rows', 'd')} | {get_val(graph_cold, 'rows', 'd')} |")
        lines.append(f"| **Illicit Labels** | {get_val(base_all, 'illicit_count', 'd')} | {get_val(base_cold, 'illicit_count', 'd')} | {get_val(graph_all, 'illicit_count', 'd')} | {get_val(graph_cold, 'illicit_count', 'd')} |")

        lines.extend(
            [
                "",
                "### Confusion Matrices",
                "",
                "| Split | Baseline Model (55 features) | Graph-Enhanced Model (60 features) |",
                "| :--- | :--- | :--- |",
                f"| **All Test Rows** | {format_cm(base_all.get('confusion_matrix', {})) if has_base else 'Pending'} | {format_cm(graph_all.get('confusion_matrix', {})) if has_graph else 'Pending'} |",
                f"| **Cold Test Subset** | {format_cm(base_cold.get('confusion_matrix', {})) if has_base else 'Pending'} | {format_cm(graph_cold.get('confusion_matrix', {})) if has_graph else 'Pending'} |",
                "",
            ]
        )

        if has_base and has_graph:
            f1_diff_all = graph_all.get("f1", 0.0) - base_all.get("f1", 0.0)
            prauc_diff_all = graph_all.get("pr_auc", 0.0) - base_all.get("pr_auc", 0.0)
            lines.extend(
                [
                    "### Honest Assessment of Graph Features Impact",
                    "",
                    f"- **F1 Delta (All Test)**: {f1_diff_all:+.4f} (Baseline {base_all.get('f1', 0.0):.4f} -> Graph-Enhanced {graph_all.get('f1', 0.0):.4f})",
                    f"- **PR-AUC Delta (All Test)**: {prauc_diff_all:+.4f} (Baseline {base_all.get('pr_auc', 0.0):.4f} -> Graph-Enhanced {graph_all.get('pr_auc', 0.0):.4f})",
                    "",
                ]
            )
        elif has_base and not has_graph:
            lines.extend(
                [
                    "> [!NOTE]",
                    "> Baseline Random Forest trained on 55 original features.",
                    "> Graph-enhanced model will be evaluated when VASP shortest path attribution (P2) is completed.",
                    "",
                ]
            )

    return "\n".join(lines) + "\n"


def main() -> int:
    """Generate reports/RESULTS.md from JSON metrics."""
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    content = generate_results_markdown()
    with RESULTS_MD.open("w", encoding="utf-8") as f:
        f.write(content)
    print(f"Generated {RESULTS_MD} successfully.")
    return 0


if __name__ == "__main__":
    main()
